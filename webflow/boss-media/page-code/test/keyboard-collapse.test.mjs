import { createRequire } from 'module';
const require = createRequire('/opt/node22/lib/node_modules/');
const { chromium } = require('playwright');
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 666 }, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
await page.goto('file:///tmp/kbtest/page.html');
const st = () => page.evaluate(() => ({ doc: document.documentElement.scrollHeight, ih: innerHeight, formTop: Math.round(document.getElementById('f').getBoundingClientRect().top + scrollY), coarse: matchMedia('(pointer: coarse)').matches }));
await page.evaluate(() => document.getElementById('f').scrollIntoView());
console.log('before     ', await st());
await page.focus('#i');
await page.setViewportSize({ width: 390, height: 337 });
await page.waitForTimeout(100);
console.log('kbd open   ', await st());
await page.focus('#j');
await page.waitForTimeout(300);
console.log('next field ', await st());
await page.evaluate(() => document.activeElement.blur());
await page.waitForTimeout(50);
await page.setViewportSize({ width: 390, height: 666 });
await page.waitForTimeout(400);
console.log('kbd closed ', await st(), 'inline left:', await page.evaluate(() => [...document.querySelectorAll('[style]')].map(e => e.className + ':' + e.getAttribute('style'))));
// control: no guard
const p2 = await ctx.newPage();
const html = (await import('fs')).readFileSync('/tmp/kbtest/page.html','utf8').replace(/<script>[\s\S]*?<\/script>/, '');
await p2.setViewportSize({ width: 390, height: 666 });
await p2.setContent(html);
const d1 = await p2.evaluate(() => document.documentElement.scrollHeight);
await p2.focus('#i'); await p2.setViewportSize({ width: 390, height: 337 }); await p2.waitForTimeout(100);
console.log('CONTROL without guard: doc', d1, '->', await p2.evaluate(() => document.documentElement.scrollHeight));
await browser.close();
